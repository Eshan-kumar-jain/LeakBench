#!/usr/bin/env python3
"""Turn results/results.jsonl (one line per trial) into a summary table.

For each task x attempt:
  - pass rate with a 95% Wilson confidence interval (better than +/-1.96*SE when n is small
    or the rate is near 0 or 1)
  - mean hidden AUC with a 95% interval (mean +/- 1.96 * standard error)
  - mean reported-minus-hidden gap: positive means the pipeline overstated its own score
  - which checks failed, and how often
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def wilson(passes: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (np.nan, np.nan)
    p = passes / n
    centre = (p + z**2 / (2 * n)) / (1 + z**2 / n)
    half = z * np.sqrt(p * (1 - p) / n + z**2 / (4 * n**2)) / (1 + z**2 / n)
    return (centre - half, centre + half)


def mean_ci(x: pd.Series) -> str:
    x = x.dropna()
    if len(x) == 0:
        return "n/a"
    if len(x) == 1:
        return f"{x.iloc[0]:.3f}"
    se = x.std(ddof=1) / np.sqrt(len(x))
    return f"{x.mean():.3f} ± {1.96 * se:.3f}"


def main():
    df = pd.read_json(ROOT / "results" / "results.jsonl", lines=True)

    rows = []
    for (task, attempt), g in df.groupby(["task", "attempt"], sort=False):
        n, passes = len(g), int(g["reward"].sum())
        lo, hi = wilson(passes, n)
        failed = g["failed_checks"].explode().dropna().value_counts()
        rows.append({
            "task": task,
            "attempt": attempt,
            "runs": n,
            "pass rate": f"{passes}/{n} [{lo:.2f}, {hi:.2f}]",
            "reported AUC": mean_ci(g["reported_val_auc"]),
            "hidden AUC": mean_ci(g["hidden_auc"]),
            "overstatement": f"{g['gap'].mean():+.3f}",
            "failed checks": "; ".join(f"{c} ({k}/{n})" for c, k in failed.items()) or "none",
        })
    table = pd.DataFrame(rows)

    overall = df.groupby("attempt", sort=False)["reward"].agg(["sum", "count"])
    overall["pass rate [95% CI]"] = [
        f"{s}/{c} [{wilson(s, c)[0]:.2f}, {wilson(s, c)[1]:.2f}]" for s, c in zip(overall["sum"], overall["count"])]

    md = ["# LeakBench results", "",
          "Generated by `analysis/analyze.py` from `results/results.jsonl`. "
          "Pass rate intervals are 95% Wilson intervals; AUC intervals are mean ± 1.96 × standard error over seeds. "
          "Overstatement = reported validation AUC minus AUC on the hidden data (positive = the pipeline flattered itself).", "",
          "## By task and attempt", "", table.to_markdown(index=False), "",
          "## Overall by attempt", "", overall[["pass rate [95% CI]"]].to_markdown(), ""]
    (ROOT / "results" / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
